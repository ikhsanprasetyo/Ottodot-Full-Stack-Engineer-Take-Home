import fs from 'fs';
import path from 'path';

const PROVINCES_URL = 'https://www.emsifa.com/api-wilayah-indonesia/api/provinces.json';
const CITIES_BASE_URL = 'https://www.emsifa.com/api-wilayah-indonesia/api/regencies';

function capitalizeWords(str) {
  return str.toLowerCase().replace(/\b\w/g, (char) => char.toUpperCase());
}

async function fetchIndoData() {
  console.log('Fetching provinces...');
  const provincesRes = await fetch(PROVINCES_URL);
  const provinces = await provincesRes.json();

  const consolidatedData = [];

  for (const province of provinces) {
    console.log(`Fetching cities for ${province.name}...`);
    const citiesRes = await fetch(`${CITIES_BASE_URL}/${province.id}.json`);
    const cities = await citiesRes.json();

    consolidatedData.push({
      id: province.id,
      name: capitalizeWords(province.name),
      cities: cities.map((c) => ({
        id: c.id,
        name: capitalizeWords(c.name)
      }))
    });
  }

  const outputDir = path.resolve('lib/constants');
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  const outputPath = path.join(outputDir, 'indonesia-regions.ts');
  const content = `// This file is auto-generated by fetch-indo-data.mjs
export type City = {
  id: string;
  name: string;
};

export type Province = {
  id: string;
  name: string;
  cities: City[];
};

export const INDONESIA_REGIONS: Province[] = ${JSON.stringify(consolidatedData, null, 2)};
`;

  fs.writeFileSync(outputPath, content);
  console.log(`Successfully saved ${consolidatedData.length} provinces to ${outputPath}`);
}

fetchIndoData().catch(console.error);
